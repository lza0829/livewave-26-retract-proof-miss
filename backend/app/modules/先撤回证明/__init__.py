"""先撤回证明（已实现 · 乙：证明号换审计行）。

题面：同一迟到事件第二次走进修正入口，接口仍回「已处理」，必须先撤回证明号兜底——
首撤成功同票落证明（事件编号、窗键、首撤哈希、证明号），二次入口按架构消化证明号，半截失败整票回滚。

全局只贯彻一种架构，本库选定 **乙：证明号换审计行**，两取舍的正确性分叉在此显式留档：

| 维度 | 甲：证明号短路 | 乙：证明号换审计行（本库） |
| --- | --- | --- |
| 二次入口见证明号 | 整票短路，不写事件行、不写业务撤回行，也不强制审计 | 必须落一条唯一键含证明号的命中审计行（撤回幂等审计.证明号，命中次数+1） |
| 业务撤回行 | 恒 1 行（短路保证） | 恒 1 行（撤回单_幂等锚点 唯一索引硬拒第二笔） |
| 窗合计 | 不二次累加 | 不二次累加（锚点闸 + 证明号核对双重排除） |
| 无证明号 | —— | 不得只靠窗键去重蒙混：有撤回无证明即判分叉，整票回滚 |
| 命中点留痕 | 无强制审计 | 命中次数/末次批次可稽核，核证只读接口可四方对账 |

硬约束落点：
- 禁止命中成功而证明空：首撤与证明同票落库（装载.py 单写事务，落证明失败即整票回滚，不吞异常）；
- 禁止持证明号仍把累计再加一遍：二次入口只累加命中审计，绝不动窗合计与业务撤回行；
- 禁止证明号与撤回簿行数分叉还提交：装载提交前互证 + 贯验窗互证 + 本模块核证只读接口三方把守。

协同面：迟到入流写闸（app/services/装载.py）、撤回簿（撤回单）、热度窗页（热度窗）、
窗互证（app/services/贯验.py）、只读接口 GET /api/核证/先撤回证明。
"""
import hashlib

状态 = "已实现"
口径 = "证明号换审计行"


def 首撤哈希(窗键: str, 事件编号: str, 旧赞: int, 新赞: int, 旧送: int, 新送: int) -> str:
    """首笔业务撤回的内容哈希：提交到 (窗键, 事件编号, 旧值→新值)，可重算核证。"""
    料 = f"首撤|{窗键}|{事件编号}|{旧赞}|{新赞}|{旧送}|{新送}"
    return hashlib.sha256(料.encode("utf-8")).hexdigest()[:16]


def 证明号(窗键: str, 事件编号: str, 哈希: str) -> str:
    """证明号：由 (窗键, 事件编号, 首撤哈希) 派生，全局唯一、可重算核证。"""
    料 = f"证明|{窗键}|{事件编号}|{哈希}"
    return "证-" + hashlib.sha256(料.encode("utf-8")).hexdigest()[:12]


def 排证明(窗键: str, 事件编号: str, 旧赞: int, 新赞: int, 旧送: int, 新送: int) -> tuple:
    """纯计算 (首撤哈希, 证明号)，不落库；首撤落库与核证重算共用同一口径。"""
    哈 = 首撤哈希(窗键, 事件编号, 旧赞, 新赞, 旧送, 新送)
    return 哈, 证明号(窗键, 事件编号, 哈)


def 落证明(conn, *, 事件编号: str, 窗键: str, 首撤哈希值: str, 证明号值: str, 时刻: str) -> str:
    """首撤同票落证明。任何失败（唯一键撞车等）直接抛异常，由调用方整票回滚——失败闭。"""
    conn.execute(
        "INSERT INTO 先撤回证明(事件编号, 窗键, 首撤哈希, 证明号, 时刻) VALUES (?,?,?,?,?)",
        (事件编号, 窗键, 首撤哈希值, 证明号值, 时刻),
    )
    return 证明号值


def 取证明(conn, 事件编号: str, 窗键: str):
    """按 (事件编号, 窗键) 取证明行；无证明返回 None（调用方据乙口径判分叉，不得靠窗键蒙混）。"""
    return conn.execute(
        "SELECT * FROM 先撤回证明 WHERE 事件编号=? AND 窗键=?",
        (事件编号, 窗键),
    ).fetchone()


def _对账一行(conn, p) -> tuple:
    """对一条证明做四方对账：撤回簿 ↔ 命中审计 ↔ 互动事件 ↔ 热度窗。返回 ( enriched, 问题列表 )。"""
    问题 = []
    项 = dict(p)
    锚点键 = f"{p['窗键']}|{p['事件编号']}"

    撤回行 = conn.execute(
        "SELECT * FROM 撤回单 WHERE 窗键=? AND 事件编号=? AND 原因='迟到修正'",
        (p["窗键"], p["事件编号"]),
    ).fetchall()
    项["撤回行数"] = len(撤回行)
    if len(撤回行) != 1:
        问题.append(f"证明号{p['证明号']}: 撤回行数={len(撤回行)}（应恒1），证明号与撤回簿分叉")
        项["哈希核证"] = "无法重算"
    else:
        d = 撤回行[0]
        望哈希, 望号 = 排证明(d["窗键"], d["事件编号"], d["旧点赞"], d["新点赞"], d["旧送礼"], d["新送礼"])
        项["哈希核证"] = "符" if p["首撤哈希"] == 望哈希 else "不符"
        if p["首撤哈希"] != 望哈希:
            问题.append(f"证明号{p['证明号']}: 首撤哈希与撤回簿重算不符（存{p['首撤哈希']}≠算{望哈希}）")
        if p["证明号"] != 望号:
            问题.append(f"证明号{p['证明号']}: 证明号与重算不符（应{望号}）")

    审计 = conn.execute(
        "SELECT * FROM 撤回幂等审计 WHERE 锚点键=?", (锚点键,)
    ).fetchone()
    项["幂等命中"] = int(审计["命中次数"]) if 审计 else 0
    if not 审计:
        问题.append(f"证明号{p['证明号']}: 缺命中审计行（锚点{锚点键}）")
    elif 审计["证明号"] != p["证明号"]:
        问题.append(f"证明号{p['证明号']}: 命中审计证明号{审计['证明号']}不符")

    事件 = conn.execute(
        "SELECT * FROM 互动事件 WHERE 事件编号=?", (p["事件编号"],)
    ).fetchone()
    if not 事件:
        问题.append(f"证明号{p['证明号']}: 互动事件{p['事件编号']}不存在")
    elif 事件["窗键"] != p["窗键"] or 事件["命运"] != "已入窗":
        问题.append(
            f"证明号{p['证明号']}: 事件命运{事件['命运']}/窗键{事件['窗键']}与证明窗键{p['窗键']}不符"
        )

    窗 = conn.execute("SELECT * FROM 热度窗 WHERE 窗键=?", (p["窗键"],)).fetchone()
    if not 窗:
        问题.append(f"证明号{p['证明号']}: 热度窗{p['窗键']}不存在")
    else:
        项["窗状态"] = 窗["状态"]
        项["窗合计"] = {"点赞": 窗["点赞合计"], "送礼": 窗["送礼合计"], "笔数": 窗["事件笔数"]}
        agg = conn.execute(
            """SELECT COALESCE(SUM(点赞增量),0) AS 赞, COALESCE(SUM(送礼额),0) AS 送, COUNT(*) AS n
               FROM 互动事件 WHERE 窗键=? AND 命运='已入窗'""",
            (p["窗键"],),
        ).fetchone()
        if (agg["赞"], agg["送"], agg["n"]) != (窗["点赞合计"], 窗["送礼合计"], 窗["事件笔数"]):
            问题.append(
                f"证明号{p['证明号']}: 窗合计{窗['点赞合计']}/{窗['送礼合计']}/{窗['事件笔数']}"
                f"与事件合计{agg['赞']}/{agg['送']}/{agg['n']}不符（疑似持证明号又加累计）"
            )
    return 项, 问题


def 查证明(conn, 事件编号: str | None = None) -> dict:
    """先撤回证明核证只读接口（纯读，不开写事务、不产生任何副作用）。

    入参：事件编号（可空——空则核证全表最近 50 条证明）。
    出参：证明行 enriched（撤回行数/幂等命中/哈希核证/窗合计）、valid、问题；
    并反抓「撤回簿有行而证明缺失」的半截分叉（命中成功而证明空）。
    """
    问题: list = []
    if 事件编号:
        rows = conn.execute(
            "SELECT * FROM 先撤回证明 WHERE 事件编号=? ORDER BY 编号", (事件编号,)
        ).fetchall()
    else:
        rows = conn.execute("SELECT * FROM 先撤回证明 ORDER BY 编号 DESC LIMIT 50").fetchall()

    证明列 = []
    for p in rows:
        项, 项问题 = _对账一行(conn, p)
        证明列.append(项)
        问题.extend(项问题)

    # 反抓半截：撤回簿有行（迟到修正）但先撤回证明缺失
    缺sql = """
        SELECT d.窗键, d.事件编号 FROM 撤回单 d
        LEFT JOIN 先撤回证明 p ON p.窗键=d.窗键 AND p.事件编号=d.事件编号
        WHERE d.原因='迟到修正' AND d.事件编号!='' AND p.编号 IS NULL"""
    if 事件编号:
        缺 = conn.execute(缺sql + " AND d.事件编号=?", (事件编号,)).fetchall()
    else:
        缺 = conn.execute(缺sql + " LIMIT 50").fetchall()
    for r in 缺:
        问题.append(f"窗{r['窗键']}事件{r['事件编号']}: 撤回簿有行但先撤回证明缺失（命中成功而证明空）")

    事件行数 = 0
    if 事件编号:
        事件行数 = conn.execute(
            "SELECT COUNT(*) AS c FROM 互动事件 WHERE 事件编号=?", (事件编号,)
        ).fetchone()["c"]

    return {
        "口径": 口径,
        "事件编号": 事件编号 or "",
        "found": bool(证明列) or bool(缺),
        "证明数": len(证明列),
        "事件行数": 事件行数,
        "证明": 证明列,
        "valid": len(问题) == 0,
        "问题": 问题,
    }
