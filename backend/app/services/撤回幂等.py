"""撤回幂等锚点服务（口径B：窗键 + 事件编号）。

全局只贯彻一种架构，本库选定 **口径B**，两口径的正确性分叉在此显式留档，供只读接口审计区分：

| 维度 | 口径A：事件编号全局幂等 | 口径B：窗键+事件编号撤回幂等（本库） |
| --- | --- | --- |
| 幂等锚点 | 互动事件主键（事件编号） | 撤回单唯一键 (窗键, 事件编号) |
| 重复推同一迟到事件 | 入流门主键拒绝，第二次「整票跳过」，不进水位/关窗/修正入口 | 允许事件行已存在时仍走修正入口，撤回单唯一键拒绝二次 |
| 互动事件行数 | 恒 1 行（由入流门整票跳过保证） | 恒 1 行（事件主键物理守卫，重复 INSERT 失败闭） |
| 撤回单行数 | 恒 1 行（整票根本到不了撤回路径） | 恒 1 行（由部分唯一索引「撤回单_幂等锚点」硬拒二次保证） |
| 窗合计 | 不二次累加（整票跳过） | 不二次累加（合计更新以锚点 INSERT 成功为闸，锚点已存在则不更新） |
| 幂等命中审计 | 命中点在入流门，锚点=事件编号 | 命中点在撤回锚点，锚点=窗键\\|事件编号，命中次数累加 |
| 反例 | —— | 禁止「无撤回唯一键却多次加合计」（本库以唯一索引 + 锚点闸双重排除） |

两口径下「重复推同一迟到事件」后事件行与撤回单行数的**数值结论相同（均恒为 1、合计均不双加）**，
但**保证机制与命中点可区分**：A 由入流门整票跳过保证（审计锚点只认事件编号、不进修正入口），
B 由撤回锚点唯一键 + 锚点闸保证（重放走完整入口、水位与关窗扫描照常，仅在修正点被拒）。
本只读接口的 ``锚点口径`` 与 ``幂等命中`` 字段即用于暴露这一分叉。

失败闭：所有写操作在调用方的单事务内完成；撞唯一约束即抛 IntegrityError 由调用方整批回滚，
不存在「合计加了、撤回没记上」或「撤回两行、合计只加一次」的半截状态。
"""
from app.services import 时间

口径 = "窗键+事件编号撤回幂等"


def 锚点(窗键: str, 事件编号: str) -> str:
    return f"{窗键}|{事件编号}"


def 记首次(conn, 窗键: str, 事件编号: str, 批次编号: str, 处理时: str, 证明号: str = "") -> bool:
    """抢撤回幂等锚点。成功（首次）返回 True；锚点已存在（二次重放）返回 False。

    依赖 撤回幂等审计.锚点键 主键做硬互斥；并发两个写事务不会同时成功
    （SQLite 单写者 + BEGIN IMMEDIATE 串行化，后者 UPDATE 命中 0 行）。
    首次落锚即带上证明号（乙：证明号换审计行——命中审计行唯一键含证明号）。
    """
    cur = conn.execute(
        """INSERT OR IGNORE INTO 撤回幂等审计
           (锚点键, 窗键, 事件编号, 首次批次编号, 首次处理时, 命中次数, 末次处理时, 末次批次编号, 证明号)
           VALUES (?,?,?,?,?,1,?,?,?)""",
        (锚点(窗键, 事件编号), 窗键, 事件编号, 批次编号, 处理时, 处理时, 批次编号, 证明号),
    )
    return cur.rowcount == 1


def 记命中(conn, 窗键: str, 事件编号: str, 批次编号: str, 处理时: str) -> None:
    """二次重放：锚点已存在，仅累加命中审计，绝不动窗合计与撤回单。"""
    conn.execute(
        """UPDATE 撤回幂等审计
           SET 命中次数=命中次数+1, 末次处理时=?, 末次批次编号=?
           WHERE 锚点键=?""",
        (处理时, 批次编号, 锚点(窗键, 事件编号)),
    )


def 查只读(conn, 事件编号: str, 窗键: str | None = None) -> dict:
    """撤回幂等只读接口（纯读，不开写事务、不产生任何副作用）。

    入参：事件编号（必填）、窗键（可空——迟到事件可由事件时与窗长反推窗键）。
    出参含：事件编号、窗键、是否二次、合计、撤回行数、valid，以及口径分叉所需的审计字段。
    """
    事件 = conn.execute(
        "SELECT * FROM 互动事件 WHERE 事件编号=?", (事件编号,)
    ).fetchone()

    
    if not 窗键 and 事件 and 事件["窗键"]:
        窗键 = 事件["窗键"]
    if not 窗键 and 事件:
        站 = {r["键"]: r["值"] for r in conn.execute("SELECT 键, 值 FROM 站规")}
        窗长 = int(站.get("窗长秒", "60"))
        窗起 = 时间.对齐窗起(事件["事件时"], 窗长)
        窗键 = 时间.窗键(事件["房间键"], 窗起)

    问题 = []
    if not 事件:
        return {
            "事件编号": 事件编号,
            "窗键": 窗键 or "",
            "锚点口径": 口径,
            "found": False,
            "是否二次": False,
            "幂等命中": 0,
            "合计": None,
            "撤回行数": 0,
            "事件行数": 0,
            "valid": False,
            "问题": ["互动事件表无此事件编号"],
        }

    事件行数 = conn.execute(
        "SELECT COUNT(*) AS c FROM 互动事件 WHERE 事件编号=?", (事件编号,)
    ).fetchone()["c"]
    if 事件行数 != 1:
        问题.append(f"事件行数={事件行数}，主键守卫失效（应恒为1）")

    撤回行 = conn.execute(
        "SELECT * FROM 撤回单 WHERE 窗键=? AND 事件编号=? AND 原因='迟到修正' ORDER BY 编号",
        (窗键, 事件编号),
    ).fetchall()
    撤回行数 = len(撤回行)
    if 撤回行数 > 1:
        问题.append(f"撤回行数={撤回行数}，撤回幂等锚点失效（应恒≤1）")

    审计 = conn.execute(
        "SELECT * FROM 撤回幂等审计 WHERE 锚点键=?", (锚点(窗键, 事件编号),)
    ).fetchone()
    命中数 = int(审计["命中次数"]) if 审计 else 0
    是否二次 = 命中数 > 1

    证明 = conn.execute(
        "SELECT * FROM 先撤回证明 WHERE 窗键=? AND 事件编号=?", (窗键, 事件编号)
    ).fetchone()
    if 撤回行数 >= 1 and not 证明:
        问题.append("撤回簿有行但先撤回证明缺失（命中成功而证明空）")
    if 证明 and 撤回行数 != 1:
        问题.append(f"证明号{证明['证明号']}挂账但撤回行数={撤回行数}（应恒1），证明号与撤回簿分叉")
    if 证明 and 审计 and 审计["证明号"] and 审计["证明号"] != 证明["证明号"]:
        问题.append(f"命中审计证明号{审计['证明号']}与证明表{证明['证明号']}不符")

    窗 = conn.execute("SELECT * FROM 热度窗 WHERE 窗键=?", (窗键,)).fetchone()
    合计 = None
    if 窗:
        合计 = {"点赞": 窗["点赞合计"], "送礼": 窗["送礼合计"], "笔数": 窗["事件笔数"]}
        
        agg = conn.execute(
            """SELECT COALESCE(SUM(点赞增量),0) AS 赞, COALESCE(SUM(送礼额),0) AS 送, COUNT(*) AS n
               FROM 互动事件 WHERE 窗键=? AND 命运='已入窗'""",
            (窗键,),
        ).fetchone()
        if agg["赞"] != 窗["点赞合计"] or agg["送"] != 窗["送礼合计"]:
            问题.append(
                f"窗合计与事件合计不符: 窗表{窗['点赞合计']}/{窗['送礼合计']} vs 事件{agg['赞']}/{agg['送']}"
            )
        if agg["n"] != 窗["事件笔数"]:
            问题.append(f"窗笔数不符: 窗表{窗['事件笔数']} vs 事件{agg['n']}")
    else:
        问题.append("热度窗不存在（事件尚未落窗或窗键反推失败）")

    
    for r in 撤回行:
        if (r["新点赞"] - r["旧点赞"], r["新送礼"] - r["旧送礼"]) != (
            int(事件["点赞增量"]),
            int(事件["送礼额"]),
        ):
            问题.append(f"撤回单编号{r['编号']}增量与事件增量不符")
        if 窗 and (r["新点赞"], r["新送礼"]) != (窗["点赞合计"], 窗["送礼合计"]):
            问题.append(f"撤回单编号{r['编号']}新值与窗表现值不一致")

    if 命中数 >= 1 and 撤回行数 != 1:
        问题.append(f"审计已锚定但撤回行数={撤回行数}（应为1），锚点与撤回单分叉")

    return {
        "事件编号": 事件编号,
        "窗键": 窗键 or "",
        "锚点口径": 口径,
        "found": True,
        "事件命运": 事件["命运"],
        "事件行数": 事件行数,
        "撤回行数": 撤回行数,
        "是否二次": 是否二次,
        "幂等命中": 命中数,
        "证明号": 证明["证明号"] if 证明 else "",
        "首撤哈希": 证明["首撤哈希"] if 证明 else "",
        "证明时刻": 证明["时刻"] if 证明 else "",
        "首次处理时": 审计["首次处理时"] if 审计 else "",
        "末次处理时": 审计["末次处理时"] if 审计 else "",
        "首次批次编号": 审计["首次批次编号"] if 审计 else "",
        "末次批次编号": 审计["末次批次编号"] if 审计 else "",
        "合计": 合计,
        "valid": len(问题) == 0,
        "问题": 问题,
    }
